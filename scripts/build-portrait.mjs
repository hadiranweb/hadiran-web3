#!/usr/bin/env node
/**
 * تولید asset پرتره با یک منبع SVG و شناسهٔ پایدار برای هر path.
 *
 * منبع در assets/portrait می‌ماند و فقط خروجی runtime در public نوشته می‌شود.
 * هیچ tile، grid یا کپی path data در bundle جاوااسکریپت تولید نمی‌شود.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "assets", "portrait", "hadiran-portrait.source.svg");
const OUTPUT = join(ROOT, "public", "hadiran-portrait.svg");
const METADATA = join(ROOT, "src", "components", "portrait", "portrait.generated.ts");
const EXPECTED_VIEWBOX = "0 0 1174.01 1091.23";

const raw = readFileSync(SOURCE, "utf8");
const viewBoxMatch = raw.match(/viewBox="([^"]+)"/);
if (!viewBoxMatch) throw new Error("viewBox در source SVG پیدا نشد.");
const viewBox = viewBoxMatch[1].trim();
if (viewBox !== EXPECTED_VIEWBOX) {
  throw new Error(`viewBox غیرمنتظره است: ${viewBox}`);
}

const pathTagRe = /<path\b[^>]*?\/\s*>/g;
const pathTags = raw.match(pathTagRe) ?? [];
if (pathTags.length === 0) throw new Error("هیچ pathای در source SVG پیدا نشد.");

const pieceId = (index) => `portrait-piece-${String(index).padStart(4, "0")}`;
let index = 0;
const output = raw.replace(pathTagRe, (tag) => {
  const id = pieceId(index);
  index += 1;
  if (/\bid="/.test(tag)) {
    throw new Error(`source SVG از قبل id دارد: ${id}`);
  }
  return tag.replace(/^<path\b/, `<path id="${id}"`);
});

if (index !== pathTags.length) {
  throw new Error(`تعداد path ناپایدار است: matched=${pathTags.length}, written=${index}`);
}

mkdirSync(dirname(OUTPUT), { recursive: true });
mkdirSync(dirname(METADATA), { recursive: true });
writeFileSync(OUTPUT, output);

const [vx, vy, vw, vh] = viewBox.split(/[\s,]+/).map(Number);
const metadata = [
  "// AUTO-GENERATED by scripts/build-portrait.mjs — دست‌کاری نشود",
  `// منبع: assets/portrait/hadiran-portrait.source.svg | path count: ${index}`,
  "",
  `export const PORTRAIT_SOURCE = "/hadiran-portrait.svg";`,
  `export const PORTRAIT_PIECE_COUNT = ${index};`,
  `export const PORTRAIT_VIEWBOX = { x: ${vx}, y: ${vy}, w: ${vw}, h: ${vh} };`,
  "",
].join("\n");
writeFileSync(METADATA, metadata);

console.log("=== build:portrait ===");
console.log("source:   assets/portrait/hadiran-portrait.source.svg");
console.log("output:   public/hadiran-portrait.svg");
console.log(`viewBox:  ${viewBox}`);
console.log(`paths:    ${index}`);
console.log("metadata: src/components/portrait/portrait.generated.ts");
console.log("روش مصرف: یک SVG خارجی + <use> با همان فایل؛ بدون grid و بدون path data در TypeScript.");
